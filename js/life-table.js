/** 別表十六の「種類」（器具・備品と工具、無形はデータの「種類：」で分ける） */
const KIND_BY_CATEGORY = { building: '建物', building_equipment: '建物附属設備', structure: '構築物', machinery: '機械及び装置', vehicle: '車両及び運搬具', tools: '器具及び備品', intangible: '無形減価償却資産' };

/**
 * kind：種類（別表十六の「種類」）、structure：構造又は用途、detail：細目
 * @type {Array<{ id: number, category: string, kind: string, structure: string, detail: string, life: number, words: string, name: string }>}
 */
export const LIFE_TABLE = [
  ['building', BUILDING],
  ['building_equipment', BUILDING_EQUIPMENT],
  ['vehicle', VEHICLE],
  ['tools', TOOLS],
  ['machinery', MACHINERY],
  ['intangible', INTANGIBLE],
]
  .flatMap(([category, rows]) =>
    rows.map(([text, detail, life, words = '', name = '']) => {
      const [kind, structure] = text.includes('：') ? text.split('：') : [KIND_BY_CATEGORY[category], text];
      return { category, kind, structure, detail, life, words, name };
    }),
  )
  .map((e, id) => ({ id, ...e }));

/** 資産の「種類」（別表十六・少額減価償却資産の明細書の「種類」）。耐用年数表から選んだ構造で、器具・備品と工具を分ける */
export function assetKind(asset) {
  const hit = LIFE_TABLE.find((e) => e.category === asset.category && e.structure === asset.structure && (!asset.detail || e.detail === asset.detail));
  return hit?.kind ?? KIND_BY_CATEGORY[asset.category] ?? '';
}

/** 検索用に正規化する（全角・半角・カタカナとひらがな・大文字小文字・空白と記号の違いを無くす） */
export function normalizeForSearch(text) {
  return String(text ?? '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/[\s・、。,.:：()（）「」]/g, '');
}

