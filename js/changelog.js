/** '0.41.0' の形か */
export function isVersion(v) {
  return typeof v === 'string' && /^\d+\.\d+\.\d+$/.test(v);
}

/** バージョンを比べる。a が新しければ正、古ければ負、同じなら 0 */
export function compareVersions(a, b) {
  const pa = String(a).split('.').map(Number);
  const pb = String(b).split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d;
  }
  return 0;
}

/**
 * from より新しく、to 以下の版の項目（新しい順）。
 * 更新の後に「前回から何が変わったか」を出すのに使う。from が無い・不正なら空
 */
export function changesSince(changelog, from, to) {
  if (!isVersion(from)) return [];
  return changelog.filter((e) => compareVersions(e.version, from) > 0 && (!to || compareVersions(e.version, to) <= 0));
}

/**
 * 更新履歴の検証。エラーメッセージの配列を返す。
 * 先頭がアプリのバージョンと一致すること（追記の抜けを検出）、新しい順・重複なし、日付・題名・内容があること
 */
export function checkChangelog(changelog, appVersion) {
  const errors = [];
  if (!Array.isArray(changelog) || !changelog.length) return ['更新履歴がありません'];
  if (changelog[0].version !== appVersion) {
    errors.push(`更新履歴の先頭が ${changelog[0].version} です。バージョン ${appVersion} の更新内容を js/changelog.js の先頭に書いてください`);
  }
  changelog.forEach((e, i) => {
    const name = e.version || `${i + 1}番目`;
    if (!isVersion(e.version)) errors.push(`更新履歴 ${name}：バージョンは 0.1.0 の形で書いてください`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date || '')) errors.push(`更新履歴 ${name}：日付は YYYY-MM-DD で書いてください`);
    if (!e.title) errors.push(`更新履歴 ${name}：題名がありません`);
    if (!Array.isArray(e.items) || !e.items.length || e.items.some((t) => typeof t !== 'string' || !t.trim())) {
      errors.push(`更新履歴 ${name}：更新内容がありません`);
    }
    const next = changelog[i + 1];
    if (next && isVersion(e.version) && isVersion(next.version) && compareVersions(e.version, next.version) <= 0) {
      errors.push(`更新履歴 ${name}：新しい順に並べてください（次が ${next.version}）`);
    }
    if (next && e.date && next.date && e.date < next.date) errors.push(`更新履歴 ${name}：日付が次の版（${next.version}）より前です`);
  });
  return errors;
}
