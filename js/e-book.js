/**
 * 事務手続を明らかにした書類のひな形（テキスト）
 * @param {{ businessName: string, entityType: 'individual'|'corporation', version: string, today: string }} p
 */
export function ebookProcedureText({ businessName, entityType, version, today }) {
  const name = businessName || '（事業者名）';
  const manager = entityType === 'corporation' ? '経理責任者' : '事業主';
  return [
    '国税関係帳簿に係る電子計算機処理に関する事務手続',
    '',
    `事業者名：${name}`,
    `制定日：${today.replaceAll('-', '/')}`,
    '',
    '第1条（目的）',
    `　この書類は、${name}が会計ソフト「Pocket会計」で作成する仕訳帳及び総勘定元帳について、入力・確認・訂正・保存の手続を定める。`,
    '',
    '第2条（使用するシステム）',
    `　Pocket会計（バージョン ${version}）を使用する。データは使用する端末の中に保存する。`,
    '　使用する端末：（例：iPhone 1台）',
    '',
    '第3条（担当者）',
    `　管理責任者：${manager}　（氏名：　　　　　）`,
    '　入力担当者：　　　　　',
    '',
    '第4条（入力）',
    '　1　入力担当者は、領収書・請求書・通帳などの証憑を確かめて仕訳を入力する。',
    '　2　入力の期限は次のとおりとする。',
    '　　（1）現金・預金の取引：取引日の翌営業日',
    '　　（2）売掛金：請求書を発行した日の翌営業日',
    '　　（3）仕入・外注費：検収した日の翌営業日',
    '　　（4）その他：証憑を確かめてから1週間以内',
    `　3　前項にかかわらず、取引日から${LATE_INPUT_MONTHS}か月を過ぎて入力する場合は、その理由を摘要に記す。`,
    '',
    '第5条（確認と訂正・削除）',
    '　1　入力担当者は、入力した日に内容を確かめ、誤りは速やかに訂正する。',
    '　2　仕訳の訂正・削除の履歴は Pocket会計が自動で記録する。履歴を消す操作はしない。',
    `　3　一度確認した仕訳の訂正・削除は、${manager}の了承を得て行う。`,
    '　4　決算を確定した会計期間は、「前期を締める」で変更できないようにする。',
    '',
    '第6条（保存）',
    '　1　毎月末に Pocket会計のバックアップファイルを書き出し、使用する端末とは別の場所に保存する。',
    '　2　帳簿のデータは、法令で定める保存期間が満了するまで保存する。',
    '　3　端末を買い替えるときは、バックアップファイルで新しい端末にデータを移し、移したことを確かめてから古い端末のデータを消す。',
    '',
    '第7条（出力）',
    '　税務職員から求められたときは、帳簿を画面に表示し、又は印刷・CSV 出力して速やかに提示する。',
    '',
    '附則',
    `　この手続は、${today.replaceAll('-', '/')}から適用する。`,
  ].join('\n');
}
