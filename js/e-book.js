/**
 * 電子取引データの訂正及び削除の防止に関する事務処理規程のひな形（テキスト）
 * @param {{ businessName: string, entityType: 'individual'|'corporation', today: string }} p
 */
export function etradeRuleText({ businessName, entityType, today }) {
  const name = businessName || '（事業者名）';
  const corp = entityType === 'corporation';
  const d = today.replaceAll('-', '/');
  return [
    '電子取引データの訂正及び削除の防止に関する事務処理規程',
    '',
    `事業者名：${name}`,
    `制定日：${d}`,
    '',
    '第1条（目的）',
    `　この規程は、電子計算機を使用して作成する国税関係帳簿書類の保存方法等の特例に関する法律第7条に定める電子取引の取引情報に係る電磁的記録（以下「電子取引データ」という。）を、${name}において適正に保存するために必要な事項を定める。`,
    '',
    '第2条（管理責任者）',
    corp ? '　この規程の管理責任者は、経理責任者とする。（氏名：　　　　　）' : `　この規程の管理責任者は、事業主とする。（氏名：　　　　　）`,
    '',
    '第3条（対象とする電子取引）',
    '　次の取引で受け取り、又は渡した請求書・領収書・見積書・注文書・納品書等のデータを対象とする。',
    '　　（1）電子メールに添付されたファイルによる取引',
    '　　（2）インターネット上のサイトやクラウドサービスで受け取り、又は渡す取引',
    '　　（3）クレジットカード・電子マネー等の利用明細のデータによる取引',
    '　　（4）その他、データで受け取り、又は渡した取引',
    '',
    '第4条（保存の方法）',
    '　1　電子取引データは、受け取り、又は渡したファイルをそのまま、会計ソフト「Pocket会計」の証憑の添付に「電子取引のデータ」として保存し、取引年月日・取引金額・取引先を入力する。',
    '　2　保存は、電子取引データを受け取り、又は渡した日から（　）日以内に行う。',
    '　3　端末の故障や紛失に備え、毎月末に Pocket会計のバックアップ（証憑も含める）を書き出し、使用する端末とは別の場所に保存する。',
    '',
    '第5条（訂正及び削除の原則禁止）',
    '　保存した電子取引データの訂正及び削除は、原則として行わない。',
    '',
    '第6条（訂正及び削除を行う場合）',
    corp
      ? '　1　業務処理上やむを得ない理由により保存した電子取引データを訂正し、又は削除するときは、次の事項を記載した「電子取引データ訂正・削除申請書」を管理責任者に提出し、承認を受ける。'
      : '　1　業務処理上やむを得ない理由により保存した電子取引データを訂正し、又は削除するときは、次の事項を「電子取引データ訂正・削除の記録」に記載する。',
    '　　（1）申請日（記録した日）',
    '　　（2）対象の電子取引データ（取引年月日・取引先・取引金額）',
    '　　（3）訂正又は削除の日',
    '　　（4）訂正又は削除の内容',
    '　　（5）訂正又は削除の理由',
    '　　（6）処理をした者',
    corp ? '　2　管理責任者は、正当な理由があると認めるときに限り承認する。訂正又は削除を終えたときは、その旨を申請書に記載して保存する。' : '　2　訂正したデータを保存するときは、訂正前のデータも削除せずに保存する。',
    corp ? '　3　訂正したデータを保存するときは、訂正前のデータも削除せずに保存する。' : null,
    '',
    '第7条（保存期間）',
    `　電子取引データ及び前条の${corp ? '申請書' : '記録'}は、国税に関する法律の規定により保存しなければならない期間が満了するまで保存する。`,
    '',
    '附則',
    `　この規程は、${d}から施行する。`,
  ]
    .filter((l) => l !== null)
    .join('\n');
}
